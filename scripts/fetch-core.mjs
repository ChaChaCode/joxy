import { mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'resources', 'xray');
const version = '26.10.31';
await mkdir(directory, { recursive: true });
const release = await fetch(`https://api.github.com/repos/XTLS/Xray-core/releases/tags/v${version}`, { headers: { 'User-Agent': 'JOXY-build' } }).then((r) => { if (!r.ok) throw new Error(`GitHub HTTP ${r.status}`); return r.json(); });
const asset = release.assets.find((a) => a.name === 'Xray-windows-64.zip');
if (!asset?.digest?.startsWith('sha256:')) throw new Error('Official SHA256 is missing');
const archive = path.join(directory, 'download.zip');
const response = await fetch(asset.browser_download_url);
if (!response.ok) throw new Error(`Download HTTP ${response.status}`);
const bytes = Buffer.from(await response.arrayBuffer());
const sha256 = createHash('sha256').update(bytes).digest('hex');
if (`sha256:${sha256}` !== asset.digest) throw new Error('Xray archive SHA256 mismatch');
await writeFile(archive, bytes);
if (process.platform !== 'win32') throw new Error('Run the Windows packaging step on Windows');
const escape = (s) => `'${s.replaceAll("'", "''")}'`;
const script = `Add-Type -AssemblyName System.IO.Compression.FileSystem; $zip=[IO.Compression.ZipFile]::OpenRead(${escape(archive)}); try { foreach($n in @('xray.exe','LICENSE','wintun.dll','LICENSE-Wintun')) { $entry=$zip.GetEntry($n); if(-not $entry){throw 'Missing core file'}; [IO.Compression.ZipFileExtensions]::ExtractToFile($entry, (Join-Path ${escape(directory)} $n), $true) } } finally { $zip.Dispose() }`;
execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-EncodedCommand', Buffer.from(script, 'utf16le').toString('base64')], { windowsHide: true });
const binarySha256 = createHash('sha256').update(await readFile(path.join(directory, 'xray.exe'))).digest('hex');
const wintunSha256 = createHash('sha256').update(await readFile(path.join(directory, 'wintun.dll'))).digest('hex');
await writeFile(path.join(directory, 'manifest.json'), JSON.stringify({ version, archiveSha256: sha256, binarySha256, wintunSha256, source: release.html_url }, null, 2));
await rm(archive);
console.log(`Verified and prepared Xray ${version} (${binarySha256.slice(0, 12)})`);
